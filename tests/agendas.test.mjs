import assert from 'node:assert/strict';
import {crossAgenda,relatedBlocks,monday,clampDate,unmatchedBlocks} from '../src/agenda-model.ts';
const p={id:'p1',name:'Profesional Fictício',profession:'Medicina',classification:'regular',establishments:['Los Olivos']};
const session={id:'s1',period_id:'q4',professional_id:'p1',establishment:'Los Olivos',agenda_name:'Consulta general',agenda_code:'001',service_day:'2026-10-28',starts_at:'08:00',ends_at:'12:00',capacity:12};
const b={id:'b',Profesional:' PROFESIONAL FICTICIO ',Establecimiento:'LOS OLIVOS',Agendas:['CONSULTA GENERAL'],Fecha_Inicio:'2026-10-28',Fecha_Termino:'2026-10-28',Tipo_Horario:'JORNADA COMPLETA',archived:0};
assert.equal(crossAgenda(session,p,[]).state,'scheduled');
assert.equal(crossAgenda(session,p,[b]).state,'blocked');
assert.equal(crossAgenda(session,p,[{...b,Establecimiento:'Buenos Aires'}]).state,'scheduled');
assert.equal(crossAgenda(session,p,[{...b,Agendas:['Otra agenda']}]).state,'scheduled');
assert.equal(crossAgenda(session,p,[{...b,Profesional:'Persona diferente'}]).state,'scheduled');
assert.equal(crossAgenda(session,p,[{...b,archived:1}]).state,'scheduled');
assert.equal(crossAgenda(session,p,[{...b,Fecha_Termino:'2026-10-27'}]).state,'scheduled');
assert.equal(crossAgenda(session,p,[{...b,Agendas:['001']}]).state,'blocked');
const part={...b,Tipo_Horario:'RANGO HORARIO',Hora_Inicio:'09:00',Hora_Termino:'10:00'};
assert.equal(crossAgenda(session,p,[part]).state,'partial');
assert.equal(crossAgenda(session,p,[part,part]).blockedMinutes,60);
assert.equal(crossAgenda(session,p,[{...part,Hora_Inicio:'08:00',Hora_Termino:'10:00'},{...part,Hora_Inicio:'10:00',Hora_Termino:'12:00'}]).state,'blocked');
assert.equal(crossAgenda(session,p,[{...part,Hora_Inicio:'12:00',Hora_Termino:'13:00'}]).state,'scheduled');
assert.equal(crossAgenda(session,p,[{...b,Tipo_Horario:'MEDIA JORNADA',Media_Jornada:'AM'}]).state,'blocked');
assert.equal(crossAgenda(session,p,[{...b,Tipo_Horario:'MEDIA JORNADA',Media_Jornada:'PM'}]).state,'scheduled');
assert.equal(crossAgenda({...session,starts_at:'11:00',ends_at:'13:00'},p,[{...b,Tipo_Horario:'MEDIA JORNADA',Media_Jornada:'AM'}]).state,'partial');
assert.equal(crossAgenda(session,p,[{...b,Tipo_Horario:'NO INFORMADO'}]).state,'uncertain');
assert.equal(crossAgenda({...session,starts_at:null,ends_at:null},p,[part]).state,'uncertain');
assert.equal(crossAgenda({...session,starts_at:null,ends_at:null},p,[b]).state,'blocked');
assert.equal(monday('2026-11-01'),'2026-10-26');
const period={id:'q4',starts_on:'2026-10-01',ends_on:'2026-12-31'};
assert.equal(clampDate('2027-01-01',period),'2026-12-31');
assert.equal(unmatchedBlocks([b],{periods:[period],sessions:[],professionals:[p]},period).length,1);
assert.equal(unmatchedBlocks([b],{periods:[period],sessions:[session],professionals:[p]},period).length,0);
console.log('Calendario: 22 verificaciones de coincidencia exacta, horarios, unión de rangos, AM/PM, datos faltantes y límites de período correctas.');
